/** Admin → Intermediate Stores: move PRISMATIC to RI; returns the function that restores it. */
async function prismaticAtRi(): Promise<() => Promise<void>> {
  const stores = await api<StoreRow[]>(USERS.admin, 'GET', '/admin/intermediate-stores');
  const ri = stores.find((s) => s.code === 'RI');
  const op = stores.find((s) => s.code === 'OP');
  if (!ri || !op) throw new Error('expected the OP and RI stores');
  const cats = await api<Array<{ id: string; code: string }>>(
    USERS.aman,
    'GET',
    '/itemization/lookups/categories',
  );
  const prismatic = cats.find((c) => c.code === 'PRISMATIC')?.id ?? '';
  const before = {
    op: await api<Mapping>(USERS.admin, 'GET', `/admin/intermediate-stores/${op.id}/mapping`),
    ri: await api<Mapping>(USERS.admin, 'GET', `/admin/intermediate-stores/${ri.id}/mapping`),
  };
  await api(USERS.admin, 'PUT', `/admin/intermediate-stores/${ri.id}/mapping`, {
    category_ids: [...before.ri.category_ids, prismatic],
    subcategory_ids: before.ri.subcategory_ids,
    reassign: true,
    reason: 'P12 E2E: RI store test products',
  });
  return async () => {
    await api(USERS.admin, 'PUT', `/admin/intermediate-stores/${op.id}/mapping`, {
      ...before.op,
      reassign: true,
      reason: 'P12 E2E: restore the default mapping',
    });
    await api(USERS.admin, 'PUT', `/admin/intermediate-stores/${ri.id}/mapping`, {
      ...before.ri,
      reassign: true,
      reason: 'P12 E2E: restore the default mapping',
    });
  };
}

async function gsByNo(gsNo: string): Promise<Gs> {
  const res = await api<{ items: Gs[] }>(USERS.gate, 'GET', `/gs?q=${encodeURIComponent(gsNo)}`);
  const hit = res.items.find((g) => g.gs_no === gsNo);
  if (!hit) throw new Error(`goods slip ${gsNo} not found`);
  return hit;
}

async function liveSlips(gs: Gs): Promise<SlipSummary[]> {
  const res = await api<{ items: SlipSummary[] }>(
    USERS.rm,
    'GET',
    `/transfer-slips?q=${encodeURIComponent(gs.gs_no)}&page_size=100`,
  );
  return res.items.filter((s) => s.status !== 'VOIDED' && s.gs_nos.includes(gs.gs_no));
}

