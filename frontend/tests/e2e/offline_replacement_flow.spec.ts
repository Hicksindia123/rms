/**
 * Phase P12 (docs/RMS_PHASE_PROMPTS_20-11-2026.md): the whole 12-step OFFLINE RETURN →
 * REPLACEMENT flow against the REAL local stack, at 1280 px and 360 px, zero console errors.
 *
 * Goods slip A goes through every screen in the browser: gate (courier, 2 cartons) → unboxing (one
 * video per carton) → items (one DT, one OP, one RI product) → "Replacement" → categorisation →
 * Lock. B (DT + OP) and C (RI) are locked through the API. Then, in the browser: the RM selects all
 * three and generates one slip per Intermediate Store (multi-GS) → each store acknowledges its
 * slip → routes its goods to a department (DIN) → receives them back → analyses (A: DT Dispatch
 * New, OP Dispatch Repaired, RI Not Allowed and sends A for Management approval; B: Dispatch New /
 * Dispatch Repaired; C: Not Allowed → on hold) → Management changes A's first line to Issue CN and
 * approves (e-approval stamp) → Accounts enters B's Challan (challan only) and A's Challan + Credit
 * Note → Dispatch Slips ready for Dispatch.
 *
 * Also: the Complete Sales Return branch parks the goods slip (SALES_RETURN_HOLD), and an Edit
 * Request → Management edit → transfer slip voided → regenerated by the RM.
 *
 * Needs `scripts/reset-db.ps1 -SkipBackup`, the API (RMS_E2E_API) and the web app (RMS_E2E_PORT);
 * run with --workers=1. Runs on the desktop Chrome project and sets each width itself.
 */
