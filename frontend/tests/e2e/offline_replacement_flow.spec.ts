async function itemsInBrowser(
  browser: Browser,
  vp: (typeof WIDTHS)[number],
  gs: Gs,
  lines: Array<[ProductInfo, number]>,
) {
  const d = await open(browser, USERS.aman, `/gs/${gs.id}/itemization`, vp.width, vp.height);
  const page = d.page;
  await expect(page.getByText(gs.gs_no).first()).toBeVisible();
  for (const [i, [p, qty]] of lines.entries()) {
    const editor = page.getByTestId('line-editor').last();
    await editor.locator('#line-new-product input').fill(p.code);
    await page.getByRole('option', { name: p.name }).first().click();
    await editor.getByRole('spinbutton', { name: /As per document/ }).fill(String(qty));
    await editor.getByRole('spinbutton', { name: 'Physically received' }).fill(String(qty));
    await editor.getByRole('button', { name: 'Add line' }).click();
    await expect(page.getByRole('button', { name: `Edit line ${String(i + 1)}` })).toBeVisible({
      timeout: 20_000,
    });
  }
  await expectNoHorizontalOverflow(page);
  await page.getByTestId('items-next').click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Replacement', { exact: true }).check();
  await page.getByTestId('return-choice-confirm').click();
  await expect.poll(() => gsStatus(gs.id)).toBe('CATEGORISATION');

  // Categorisation: every piece of each line in its first condition (G-19), then Lock.
  for (const [i, [p, qty]] of lines.entries()) {
    await page.getByRole('button', { name: `Edit line ${String(i + 1)}` }).click();
    const split = page.getByTestId('line-split-editor');
    await split.getByLabel(p.bucketLabel, { exact: true }).fill(String(qty));
    await expect(page.getByTestId('split-total')).toHaveText(
      `Split ${String(qty)} / Physical ${String(qty)}`,
    );
    await page.getByRole('button', { name: 'Save line' }).click();
    await expect(page.getByTestId('line-split-editor')).toHaveCount(0, { timeout: 20_000 });
  }
  await expect(page.getByTestId('lock-categorisation')).toBeEnabled();
  await expectNoHorizontalOverflow(page);
  await page.getByTestId('lock-categorisation').click();
  await page.getByTestId('lock-confirm').click();
  await expect(page.getByTestId('categorisation-locked')).toBeVisible({ timeout: 20_000 });
  await expect.poll(() => gsStatus(gs.id)).toBe('PENDING_TRANSFER_SLIP');
  await done(d, `${vp.name}-03-locked`);
}

