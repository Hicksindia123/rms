      const gs = await createGs(`P12SR${String(vp.width)}`);
      await unboxed(gs);
      await addItem(gs.id, dmt.id, 2, 2);
      const re = await open(browser, USERS.aman, `/gs/${gs.id}/itemization`, vp.width, vp.height);
      await re.page.getByTestId('items-next').click();
      await re.page
