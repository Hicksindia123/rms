/** A product of the category whose item field profile offers a condition bucket. */
async function productInfo(category: string): Promise<ProductInfo> {
  const cats = await api<Array<{ id: string; code: string }>>(
    USERS.aman,
    'GET',
    '/itemization/lookups/categories',
  );
  const cat = cats.find((c) => c.code === category);
  if (!cat) throw new Error(`no category ${category}`);
  const rows = await api<Array<{ id: string; code: string; name: string }>>(
    USERS.aman,
    'GET',
    `/itemization/lookups/products?q=&limit=50&category_id=${cat.id}`,
  );
  for (const r of rows) {
    const fields = await api<{
      allowed_buckets: Array<{ field_code: string; field_label: string }>;
    }>(USERS.aman, 'GET', `/itemization/lookups/products/${r.id}/fields`);
    const first = fields.allowed_buckets[0];
    if (first) {
      return { ...r, bucket: first.field_code, bucketLabel: first.field_label };
    }
  }
  throw new Error(`no ${category} product with condition buckets`);
}

