async function fullFlow(browser: Browser, vp: (typeof WIDTHS)[number]): Promise<void> {
  const p: Record<StoreCode, ProductInfo> = {
    DT: await productInfo(CATEGORY.DT),
    OP: await productInfo(CATEGORY.OP),
    RI: await productInfo(CATEGORY.RI),
  };

  // Steps 1 – 2c for A in the browser; B and C locked through the API.
  const a = await gateInBrowser(browser, vp);
  await unboxInBrowser(browser, vp, a);
  await itemsInBrowser(browser, vp, a, [
    [p.DT, 3],
    [p.OP, 2],
    [p.RI, 1],
  ]);
  const w = String(vp.width);
  const b = await lockedGs(`P12B${w}`, [
    [p.DT, 2],
    [p.OP, 1],
  ]);
  const c = await lockedGs(`P12C${w}`, [[p.RI, 2]]);

  // Step 2d: one slip per store, multi-GS (OP: A + B, DT: A + B, RI: A + C).
  await generateSlips(browser, vp, [a, b, c]);
  const slips = await liveSlips(a);
  expect(slips.map((s) => s.store.code).sort()).toEqual(['DT', 'OP', 'RI']);
  const slipOf = (store: StoreCode) => {
    const s = slips.find((x) => x.store.code === store);
    if (!s) throw new Error(`no ${store} slip`);
    return s;
  };
  expect(slipOf('OP').gs_nos.sort()).toEqual([a.gs_no, b.gs_no].sort());
  expect(slipOf('RI').gs_nos.sort()).toEqual([a.gs_no, c.gs_no].sort());

  // Step 3: each store acknowledges its own slip.
  for (const store of ['DT', 'OP', 'RI'] as const) {
    await acknowledge(browser, vp, store, slipOf(store));
  }
  for (const gs of [a, b, c]) await expect.poll(() => gsStatus(gs.id)).toBe('STORE_ACKNOWLEDGED');

  // Steps 4 – 6: route to a department, receive back.
  const parts: Array<[StoreCode, Gs, number]> = [
    ['DT', a, 3],
    ['OP', a, 2],
    ['RI', a, 1],
    ['DT', b, 2],
    ['OP', b, 1],
    ['RI', c, 2],
  ];
  for (const [store, gs, qty] of parts) await route(browser, vp, store, gs, qty);
  for (const [store, gs] of parts) await receive(browser, vp, store, gs);

  // Steps 7 – 8: analysis. A's last store sends it for Management approval with its part.
  await analyse(browser, vp, 'DT', a, 'Dispatch New Piece');
  await analyse(browser, vp, 'OP', a, 'Dispatch Repaired Piece');
  await analyse(browser, vp, 'RI', a, 'Not Allowed', 'Party asks for a credit note');
  await expect.poll(() => gsStatus(a.id)).toBe('ANALYSIS_COMPLETED');
  await analyse(browser, vp, 'DT', b, 'Dispatch New Piece');
  await analyse(browser, vp, 'OP', b, 'Dispatch Repaired Piece');
  await expect.poll(() => gsStatus(b.id)).toBe('ACCOUNTS_PENDING');
  await analyse(browser, vp, 'RI', c, 'Not Allowed');
  await expect.poll(() => gsStatus(c.id)).toBe('NOT_ALLOWED_HOLD'); // Q21

  // Steps 9 – 10: Management → Issue CN + e-approval stamp → Accounts.
  await managementApproves(browser, vp, a);

  // Steps 11 – 12: Accounts per goods slip → Dispatch Slip.
  await accountsCompletes(browser, vp, b, false);
  await accountsCompletes(browser, vp, a, true);

  // C is on hold, not at Accounts.
  const acc = await open(browser, USERS.accounts, '/accounts-entry', vp.width, vp.height);
  await expect(acc.page.getByRole('heading', { name: /Accounts Entry/ })).toBeVisible();
  await expect(acc.page.getByRole('button').filter({ hasText: c.gs_no })).toHaveCount(0);
  await acc.page.getByRole('button', { name: 'On hold' }).click();
  const held = acc.page
    .getByRole('list', { name: 'Goods slips on hold' })
    .getByRole('listitem')
    .filter({ hasText: c.gs_no });
  await expect(held).toBeVisible({ timeout: 20_000 });
  // The badge shows the configured GS_STATUS label (rule e), not the code.
  await expect(held).toContainText('On Hold – Not Allowed');
  await done(acc, `${vp.name}-11-on-hold`);

  // Dispatch sees both Dispatch Slips.
  const d = await open(browser, USERS.dispatch, '/dispatch-slips', vp.width, vp.height);
  await expect(d.page.getByText(a.gs_no).first()).toBeVisible({ timeout: 20_000 });
  await expect(d.page.getByText(b.gs_no).first()).toBeVisible();
  await done(d, `${vp.name}-12-dispatch`);
}

