import { useCallback } from 'react';
import { ArrowLeft, Printer } from 'lucide-react';

import { Button, ErrorState, LoadingState } from '@/components/ui';
import { formatDateTime } from '@/features/goods-slips/format';
import { useApiQuery } from '@/hooks/useApiQuery';

import { reportsApi, type ReportPrint } from './api';
import { formatCell, formatTotal, isNumeric } from './format';

interface Props {
  code: string;
  query: URLSearchParams;
  onBack: () => void;
}

/** Logo display: absolute URL or bundled asset path (e.g. /assets/logo.png). */
function isUploadedLogo(url: string | null): url is string {
  return url !== null && (/^https?:\/\//.test(url) || url.startsWith('/'));
}

/** P4-02 generic report print layout: A4 landscape, branding header, filters used, generated
 * by / at, repeating table header and CSS page numbers. */
export function ReportPrintPage({ code, query, onBack }: Props) {
  const qs = query.toString();
  const fetcher = useCallback(
    () => reportsApi.print(code, Object.fromEntries(new URLSearchParams(qs))),
    [code, qs],
  );
  const { data, error, loading, reload } = useApiQuery<ReportPrint>(fetcher);

  if (error) {
    return (
      <ErrorState
        title="The printable report could not be prepared"
        error={{ message: error.message, code: error.code, requestId: error.requestId }}
        onRetry={reload}
      />
    );
  }
  if (loading || !data) return <LoadingState label="Preparing the printable report…" />;

  return (
    <div className="report-print-screen">
      <div className="report-print__toolbar no-print">
        <Button type="button" variant="secondary" onClick={onBack}>
          <ArrowLeft size={16} aria-hidden="true" /> Back to report
        </Button>
        <Button
          type="button"
          variant="primary"
          onClick={() => {
            window.print();
          }}
        >
          <Printer size={16} aria-hidden="true" /> Print
        </Button>
      </div>

      <article className="report-print" aria-label={`${data.code} ${data.title}`}>
        <header className="report-print__header">
          <div className="report-print__brand">
            {isUploadedLogo(data.branding.logo_url) ? (
              <img src={data.branding.logo_url} alt="" className="report-print__logo" />
            ) : null}
            <span
              className="report-print__app"
              style={
                data.branding.primary_color ? { color: data.branding.primary_color } : undefined
              }
            >
              {data.branding.app_name}
            </span>
          </div>
          <h1 className="report-print__title">
            {data.code} · {data.title}
          </h1>
          <dl className="report-print__meta">
            <div>
              <dt>Generated by</dt>
              <dd>{data.generated_by}</dd>
            </div>
            <div>
              <dt>Generated at</dt>
              <dd>{formatDateTime(data.generated_at)}</dd>
            </div>
            <div>
              <dt>Rows</dt>
              <dd>
                {data.truncated
                  ? `first ${data.printed_rows.toLocaleString('en-IN')} of ${data.total_rows.toLocaleString('en-IN')} (narrow the filters or export for all rows)`
                  : data.total_rows.toLocaleString('en-IN')}
              </dd>
            </div>
          </dl>
          <div className="report-print__filters">
            <strong>Filters: </strong>
            {data.filters_used.length === 0
              ? 'none'
              : data.filters_used.map((f) => `${f.label}: ${f.value}`).join(' · ')}
          </div>
        </header>

        {data.rows.length === 0 ? (
          <p className="report-print__empty">No rows match these filters.</p>
        ) : (
          <table className="report-print__table">
            <thead>
              <tr>
                {data.columns.map((c) => (
                  <th key={c.key} className={isNumeric(c.type) ? 'num' : undefined}>
                    {c.label}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {data.rows.map((row, i) => (
                <tr key={i}>
                  {data.columns.map((c) => (
                    <td key={c.key} className={isNumeric(c.type) ? 'num' : undefined}>
                      {formatCell(c.type, row[c.key] ?? null)}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
            {data.columns.some((c) => c.total !== null) ? (
              <tfoot>
                <tr>
                  {data.columns.map((c, i) => (
                    <td key={c.key} className={isNumeric(c.type) ? 'num' : undefined}>
                      {c.total !== null
                        ? formatTotal(c, data.totals[c.key] ?? null, data.total_rows)
                        : i === 0
                          ? 'Totals'
                          : ''}
                    </td>
                  ))}
                </tr>
              </tfoot>
            ) : null}
          </table>
        )}
        <footer className="report-print__footer">
          {data.branding.app_name} · {data.code} · printed {formatDateTime(data.generated_at)}
        </footer>
      </article>
    </div>
  );
}
