"""Reports & MIS HTTP API (prompt P4-02).

Report parameters are the report's filter keys as query parameters plus page, page_size, sort,
dir and (export/print) columns=a,b,c. Unknown or repeated parameters → 422 INVALID_REPORT_PARAMS.
"""

from __future__ import annotations

from typing import Annotated, Literal
from uuid import UUID

from fastapi import APIRouter, Depends, Path, Query, Request, Response, status
from fastapi.responses import StreamingResponse

from app.core.db import UowDep
from app.core.errors import ValidationFailed
from app.core.permissions import EffectivePermissionsDep, require
from app.core.security import CurrentUser
from app.modules.reports.schemas import (
    ColumnPrefOut,
    ColumnsIn,
    ReportDataOut,
    ReportDefinitionOut,
    ReportGroupOut,
    ReportPrintOut,
    RoleColumnsIn,
    RoleColumnsOut,
    RoleRef,
    SavedFilterIn,
    SavedFilterOut,
)
from app.modules.reports.service import ReportService

router = APIRouter(tags=["reports"])

ViewUser = Annotated[CurrentUser, Depends(require("reports", "view"))]
ExportUser = Annotated[CurrentUser, Depends(require("reports", "export"))]
ConfigureUser = Annotated[CurrentUser, Depends(require("reports", "configure"))]
ReportCode = Annotated[str, Path(pattern=r"^R-[0-9]{2}$")]
RoleCode = Annotated[str, Path(pattern=r"^[A-Z][A-Z0-9_]{1,59}$")]


def get_service(uow: UowDep) -> ReportService:
    return ReportService(uow)


ServiceDep = Annotated[ReportService, Depends(get_service)]


def report_params(request: Request) -> dict[str, str]:
    seen: dict[str, str] = {}
    repeated: list[str] = []
    for key, value in request.query_params.multi_items():
        if key in seen:
            repeated.append(key)
        seen[key] = value
    if repeated:
        raise ValidationFailed(
            "Each report parameter may be given once",
            code="INVALID_REPORT_PARAMS",
            details=[{"loc": [k], "msg": "repeated parameter"} for k in sorted(set(repeated))],
        )
    return seen


ParamsDep = Annotated[dict[str, str], Depends(report_params)]


@router.get("/reports", response_model=list[ReportGroupOut])
def catalogue(
    user: ViewUser, perms: EffectivePermissionsDep, service: ServiceDep
) -> list[ReportGroupOut]:
    """Reports you may run, grouped (reports.view + each report's module permission and scope)."""
    return service.catalogue(user, perms)


@router.get("/reports/{code}", response_model=ReportDefinitionOut)
def definition(
    code: ReportCode, user: ViewUser, perms: EffectivePermissionsDep, service: ServiceDep
) -> ReportDefinitionOut:
    """Columns, filters (with choices and defaults), your visible columns and saved filters."""
    return service.definition(user, perms, code)


@router.get("/reports/{code}/data", response_model=ReportDataOut)
def data(
    code: ReportCode,
    user: ViewUser,
    perms: EffectivePermissionsDep,
    service: ServiceDep,
    params: ParamsDep,
    response: Response,
) -> ReportDataOut:
    """One page of rows (server-side sort) and totals over all filtered rows."""
    response.headers["Cache-Control"] = "private, no-store"
    return service.data(user, perms, code, params)


@router.get("/reports/{code}/export")
def export(
    code: ReportCode,
    user: ExportUser,
    perms: EffectivePermissionsDep,
    service: ServiceDep,
    params: ParamsDep,
    format: Annotated[Literal["csv", "xlsx"], Query()] = "csv",
) -> StreamingResponse:
    """All filtered rows as CSV or XLSX, streamed. 422 EXPORT_TOO_LARGE above the configured
    `report_export_max_rows`."""
    result = service.export(user, perms, code, format, params)
    return StreamingResponse(
        result.body,
        media_type=result.media_type,
        headers={
            "Content-Disposition": f'attachment; filename="{result.filename}"',
            "Cache-Control": "private, no-store",
        },
    )


@router.get("/reports/{code}/print", response_model=ReportPrintOut)
def print_report(
    code: ReportCode,
    user: ViewUser,
    perms: EffectivePermissionsDep,
    service: ServiceDep,
    params: ParamsDep,
) -> ReportPrintOut:
    """Data for the generic A4-landscape print layout (branding, filters used, generated by/at)."""
    return service.print_data(user, perms, code, params)


@router.put("/reports/{code}/columns", response_model=ColumnPrefOut)
def set_my_columns(
    code: ReportCode,
    payload: ColumnsIn,
    user: ViewUser,
    perms: EffectivePermissionsDep,
    service: ServiceDep,
) -> ColumnPrefOut:
    """Save your own visible columns for the report."""
    return service.set_my_columns(user, perms, code, payload)


@router.delete("/reports/{code}/columns", response_model=ColumnPrefOut)
def reset_my_columns(
    code: ReportCode, user: ViewUser, perms: EffectivePermissionsDep, service: ServiceDep
) -> ColumnPrefOut:
    """Forget your column choice (back to your role's default or the report default)."""
    return service.reset_my_columns(user, perms, code)


@router.post(
    "/reports/{code}/saved-filters",
    response_model=SavedFilterOut,
    status_code=status.HTTP_201_CREATED,
)
def create_saved_filter(
    code: ReportCode,
    payload: SavedFilterIn,
    user: ViewUser,
    perms: EffectivePermissionsDep,
    service: ServiceDep,
) -> SavedFilterOut:
    return service.create_saved_filter(user, perms, code, payload)


@router.delete("/reports/{code}/saved-filters/{filter_id}", status_code=status.HTTP_204_NO_CONTENT)
def delete_saved_filter(
    code: ReportCode,
    filter_id: UUID,
    user: ViewUser,
    perms: EffectivePermissionsDep,
    service: ServiceDep,
) -> Response:
    service.delete_saved_filter(user, perms, code, filter_id)
    return Response(status_code=status.HTTP_204_NO_CONTENT)


@router.get("/admin/report-column-defaults", response_model=list[RoleColumnsOut])
def list_column_defaults(user: ConfigureUser, service: ServiceDep) -> list[RoleColumnsOut]:
    """Admin default columns per report per role (§10 "Report columns")."""
    return service.list_role_columns(user)


@router.get("/admin/report-column-defaults/roles", response_model=list[RoleRef])
def column_default_roles(user: ConfigureUser, service: ServiceDep) -> list[RoleRef]:
    """Roles a default can be set for."""
    return service.roles(user)


@router.put("/admin/report-column-defaults/{code}/{role_code}", response_model=RoleColumnsOut)
def put_column_defaults(
    code: ReportCode,
    role_code: RoleCode,
    payload: RoleColumnsIn,
    user: ConfigureUser,
    service: ServiceDep,
) -> RoleColumnsOut:
    """Set the role's default columns for the report (writes config_change_log)."""
    return service.put_role_columns(user, code, role_code, payload)


@router.delete(
    "/admin/report-column-defaults/{code}/{role_code}", status_code=status.HTTP_204_NO_CONTENT
)
def delete_column_defaults(
    code: ReportCode,
    role_code: RoleCode,
    user: ConfigureUser,
    service: ServiceDep,
    reason: Annotated[str | None, Query(max_length=500)] = None,
) -> Response:
    service.delete_role_columns(user, code, role_code, reason)
    return Response(status_code=status.HTTP_204_NO_CONTENT)
