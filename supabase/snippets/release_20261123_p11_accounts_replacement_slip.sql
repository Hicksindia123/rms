-- Release 2026-11-23 - Phase P11 (DEC-71; Q19 PROVISIONAL, Q21 / Q22 CONFIRMED): Accounts per
-- goods slip. When every Intermediate Store submitted its analysis and the Management gate passes,
-- the goods slip goes to Accounts ("At Accounts") with one Replacement Slip, or stays "On Hold – Not
-- Allowed" when nothing needs a Challan or a Credit Note (Q21). Accounts enters one Challan and / or
-- one Credit Note per goods slip; completion generates the Dispatch Slip ("Pending Dispatch").
--
-- Apply to production AFTER migration 20261123000400_p11_accounts_replacement_dispatch.sql and after
-- deploying the P11 backend + frontend. Idempotent; safe to re-run:
--   psql "<admin url>" -X -v ON_ERROR_STOP=1 -f supabase/snippets/release_20261123_p11_accounts_replacement_slip.sql
-- Same configuration as supabase/seed.sql (phase prompts §0 rule 3).
begin;

-- 1. Status labels (GS_STATUS; codes fixed, labels admin-editable).
insert into public.option_items (option_set_id, code, label, allowed_status, rule_text, next_action_text,
                                 remarks, system_behavior, required_fields, sort_order, source_ref)
select os.id, v.code, v.label, 'YES', null, null, null, null, '[]'::jsonb, 74, 'DEC-71'
  from (values ('ACCOUNTS_PENDING', 'At Accounts'),
               ('NOT_ALLOWED_HOLD', 'On Hold – Not Allowed'),
               ('DISPATCH_PENDING', 'Pending Dispatch')) as v(code, label)
  join public.option_sets os on os.code = 'GS_STATUS'
on conflict (option_set_id, code) do nothing;

-- 2. "Replacement Slip": a new published version of the AC_ACTIONS_SLIP template (label only), only
--    while it still has the old default name.
do $$
declare
  v_tpl    record;
  v_layout jsonb;
begin
  select id, code, version_no, coalesce(snapshot, layout) as layout into v_tpl
    from public.print_templates
   where code = 'AC_ACTIONS_SLIP' and status = 'PUBLISHED' and name = 'Replacement Slip – A/c Actions';
  if found then
    v_layout := v_tpl.layout || jsonb_build_object(
      'header_subtitle', 'Replacement Slip',
      'footer_text', 'Computer generated by RMS. Accounts record one Challan (goods to ship) and one Credit Note (Issue CN) per goods slip.',
      'signature_blocks', jsonb_build_array(
        jsonb_build_object('label', 'Prepared By', 'role', 'Store / Management'),
        jsonb_build_object('label', 'Received By', 'role', 'Accounts')));
    update public.print_templates set status = 'RETIRED' where id = v_tpl.id;
    insert into public.print_templates (code, name, version_no, layout, status, snapshot, published_at)
    values ('AC_ACTIONS_SLIP', 'Replacement Slip',
            (select max(version_no) + 1 from public.print_templates where code = 'AC_ACTIONS_SLIP'),
            v_layout, 'PUBLISHED', v_layout, now());
  end if;
end
$$;

-- 3. In-app alert for the hold (recipients are this rule, admin-editable; email deferred, Q22).
--    Accounts is alerted by the existing AC_ACTIONS_SLIP_READY rule (ACCOUNTS role).
insert into public.notification_rules
  (event_type, name, include_context_recipients, recipient_role_codes, channels, priority, is_active)
select 'GS_NOT_ALLOWED_HOLD', 'RM & Management: goods slip on hold (all Not Allowed)',
       true, array['REPLACEMENT_MANAGER', 'MANAGEMENT'], array['IN_APP'], 'NORMAL', true
 where not exists (select 1 from public.notification_rules r where r.event_type = 'GS_NOT_ALLOWED_HOLD');

-- 4. Report: analysed goods slips waiting since before this release are routed by Management's
--    next approval (or the next store submission); none exist in production before P9 is deployed.
do $$
declare
  v_done integer;
begin
  select count(*) into v_done from public.goods_slips where status = 'ANALYSIS_COMPLETED';
  raise notice 'DEC-71: % goods slip(s) Analysis Completed (Management approval routes them to Accounts)', v_done;
end
$$;

commit;
