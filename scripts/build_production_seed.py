"""Build the one-time production seed (docs/DATABASE_MIGRATION_GUIDE.md, production audit Phase 2).

`supabase db push` applies the migrations only. Configuration (roles + permission matrix,
option catalogue, forms, workflow, settings, number series) and master data (stations, parties,
products) live in the seed files, which must be loaded ONCE into a fresh production database.

This script concatenates, in the order of supabase/config.toml [db.seed] sql_paths:
    seed.sql (without the DEMO block) + seed_stations.sql + seed_parties.sql + seed_products.sql
and wraps everything in a single transaction (all or nothing).

Usage (from the repo root; stdlib only):
    python scripts/build_production_seed.py [OUTPUT]
Default OUTPUT: supabase/.temp/production_seed.sql (git-ignored).

It refuses to write a file that still contains DEMO markers or DEMO rows.
"""

from __future__ import annotations

import hashlib
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SUPABASE = ROOT / "supabase"
DEMO_BEGIN = re.compile(r"^-- DEMO:BEGIN", re.MULTILINE)
DEMO_END = re.compile(r"^-- DEMO:END.*$", re.MULTILINE)


def seed_paths() -> list[Path]:
    config = tomllib.loads((SUPABASE / "config.toml").read_text(encoding="utf-8"))
    paths = config["db"]["seed"]["sql_paths"]
    return [(SUPABASE / p).resolve() for p in paths]


def strip_demo(text: str, name: str) -> str:
    begin = DEMO_BEGIN.search(text)
    if not begin:
        return text
    end = DEMO_END.search(text, begin.end())
    if not end:
        raise SystemExit(f"{name}: DEMO:BEGIN without DEMO:END")
    return text[: begin.start()] + text[end.end() :]


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else SUPABASE / ".temp" / "production_seed.sql"
    parts = [
        "-- RMS production seed (generated by scripts/build_production_seed.py; do not edit).",
        "-- Load ONCE into a fresh production database after `supabase db push`.",
        "-- All or nothing: any error rolls the whole seed back.",
        "begin;",
        "set local client_min_messages = warning;",
    ]
    for path in seed_paths():
        text = path.read_text(encoding="utf-8")
        cleaned = strip_demo(text, path.name)
        if "(DEMO)" in cleaned or "DEMO:" in cleaned:
            raise SystemExit(f"{path.name}: DEMO content left after stripping")
        digest = hashlib.sha256(cleaned.encode("utf-8")).hexdigest()[:16]
        parts.append(f"\n-- ===== {path.name} (sha256/16 {digest}) =====\n")
        parts.append(cleaned.rstrip() + "\n")
    parts.append("commit;\n")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes("\n".join(parts).encode("utf-8"))
    size_kb = out.stat().st_size // 1024
    print(f"wrote {out} ({size_kb} KB) from {len(seed_paths())} seed files, DEMO block removed")


if __name__ == "__main__":
    main()
